-- MySMS iam: hierarchical settings and sign-in support.
-- Settings: a product catalogue of setting definitions, and values set at tenant, institution, department,
-- class section or user scope. Effective value for a user: user > class section > primary department >
-- institution > tenant > definition default, unless a broader scope locks the value.
-- Sign-in: the tenant directory iam needs to resolve a tenant code at login without reading another schema.

-- ---------------------------------------------------------------- setting catalogue (global, like iam.permission)
CREATE TABLE iam.setting_definition (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    setting_key varchar(100) NOT NULL,
    category varchar(60) NOT NULL,
    value_type varchar(20) NOT NULL,
    allowed_values varchar(60)[],
    min_value integer,
    max_value integer,
    default_value varchar(500),
    allowed_scopes varchar(20)[] NOT NULL,
    user_editable boolean NOT NULL DEFAULT true,
    description text,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid,
    deleted_at timestamptz,
    row_version integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_setting_definition PRIMARY KEY (id),
    CONSTRAINT uq_setting_definition_setting_key UNIQUE (setting_key),
    CONSTRAINT ck_setting_definition_value_type CHECK (value_type IN ('string', 'boolean', 'integer', 'choice')),
    CONSTRAINT ck_setting_definition_choice CHECK ((value_type = 'choice') = (allowed_values IS NOT NULL)),
    CONSTRAINT ck_setting_definition_range CHECK (min_value IS NULL OR max_value IS NULL OR min_value <= max_value),
    CONSTRAINT ck_setting_definition_scopes CHECK (allowed_scopes <@ ARRAY['tenant', 'institution', 'department', 'class_section', 'user']::varchar(20)[] AND cardinality(allowed_scopes) > 0)
);
COMMENT ON TABLE iam.setting_definition IS 'Product catalogue of settings (theme, density, language...): type, allowed values, default and the scopes a value may be set at. Global: no tenant; maintained by migrations.';
COMMENT ON COLUMN iam.setting_definition.id IS 'Surrogate primary key (UUIDv7 generated by the application; database default is a v4 fallback).';
COMMENT ON COLUMN iam.setting_definition.setting_key IS 'Stable key, e.g. ui.theme.';
COMMENT ON COLUMN iam.setting_definition.category IS 'Grouping on the settings screens, e.g. appearance.';
COMMENT ON COLUMN iam.setting_definition.value_type IS 'Type of the value: string, boolean, integer or choice.';
COMMENT ON COLUMN iam.setting_definition.allowed_values IS 'Allowed values of a choice setting.';
COMMENT ON COLUMN iam.setting_definition.min_value IS 'Smallest allowed value of an integer setting.';
COMMENT ON COLUMN iam.setting_definition.max_value IS 'Largest allowed value of an integer setting.';
COMMENT ON COLUMN iam.setting_definition.default_value IS 'Value when no scope sets one.';
COMMENT ON COLUMN iam.setting_definition.allowed_scopes IS 'Scopes at which a value may be set (subset of tenant, institution, department, class_section, user).';
COMMENT ON COLUMN iam.setting_definition.user_editable IS 'Whether users may set the setting for themselves.';
COMMENT ON COLUMN iam.setting_definition.description IS 'What the setting changes.';
COMMENT ON COLUMN iam.setting_definition.sort_order IS 'Display order within its category.';
COMMENT ON COLUMN iam.setting_definition.created_at IS 'Row creation time.';
COMMENT ON COLUMN iam.setting_definition.created_by IS 'User account that created the row (audit reference to iam.user_account; not FK-constrained).';
COMMENT ON COLUMN iam.setting_definition.updated_at IS 'Last update time.';
COMMENT ON COLUMN iam.setting_definition.updated_by IS 'User account that last updated the row (audit reference to iam.user_account; not FK-constrained).';
COMMENT ON COLUMN iam.setting_definition.deleted_at IS 'Soft-delete marker; NULL = live row.';
COMMENT ON COLUMN iam.setting_definition.row_version IS 'Optimistic-locking version.';

-- ---------------------------------------------------------------- setting values (tenant-owned)
CREATE TABLE iam.setting_value (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    tenant_id uuid NOT NULL,
    scope_type varchar(20) NOT NULL,
    scope_id uuid,
    setting_key varchar(100) NOT NULL,
    value varchar(500) NOT NULL,
    is_locked boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid,
    deleted_at timestamptz,
    row_version integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_setting_value PRIMARY KEY (id),
    CONSTRAINT ck_setting_value_scope_type CHECK (scope_type IN ('tenant', 'institution', 'department', 'class_section', 'user')),
    CONSTRAINT ck_setting_value_scope_id CHECK ((scope_type = 'tenant') = (scope_id IS NULL)),
    CONSTRAINT ck_setting_value_user_unlocked CHECK (NOT (scope_type = 'user' AND is_locked))
);
COMMENT ON TABLE iam.setting_value IS 'A setting value at one scope. Effective value for a user: user > class section > primary department > institution > tenant > default, unless a broader scope locks it.';
COMMENT ON COLUMN iam.setting_value.id IS 'Surrogate primary key (UUIDv7 generated by the application; database default is a v4 fallback).';
COMMENT ON COLUMN iam.setting_value.tenant_id IS 'Owning tenant (platform.tenant; logical, isolation by RLS).';
COMMENT ON COLUMN iam.setting_value.scope_type IS 'Level the value applies to: tenant, institution, department, class_section or user.';
COMMENT ON COLUMN iam.setting_value.scope_id IS 'Institution (org), department (org), class section (academics) or user account (iam) the value applies to; NULL for tenant. Polymorphic like iam.user_role.scope_id.';
COMMENT ON COLUMN iam.setting_value.setting_key IS 'The setting (iam.setting_definition.setting_key).';
COMMENT ON COLUMN iam.setting_value.value IS 'The value, as text in the setting type.';
COMMENT ON COLUMN iam.setting_value.is_locked IS 'Narrower scopes and users cannot override the value (never set on user scope).';
COMMENT ON COLUMN iam.setting_value.created_at IS 'Row creation time.';
COMMENT ON COLUMN iam.setting_value.created_by IS 'User account that created the row (audit reference to iam.user_account; not FK-constrained).';
COMMENT ON COLUMN iam.setting_value.updated_at IS 'Last update time.';
COMMENT ON COLUMN iam.setting_value.updated_by IS 'User account that last updated the row (audit reference to iam.user_account; not FK-constrained).';
COMMENT ON COLUMN iam.setting_value.deleted_at IS 'Soft-delete marker; NULL = live row.';
COMMENT ON COLUMN iam.setting_value.row_version IS 'Optimistic-locking version.';
ALTER TABLE iam.setting_value ADD CONSTRAINT fk_setting_value_setting_key FOREIGN KEY (setting_key) REFERENCES iam.setting_definition (setting_key) ON DELETE RESTRICT;
CREATE INDEX ix_setting_value_setting_key ON iam.setting_value (setting_key);
CREATE INDEX ix_setting_value_tenant_id ON iam.setting_value (tenant_id);
CREATE INDEX ix_setting_value_scope ON iam.setting_value (tenant_id, scope_type, scope_id) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_setting_value_scope_key ON iam.setting_value (tenant_id, scope_type, scope_id, setting_key) NULLS NOT DISTINCT WHERE deleted_at IS NULL;
ALTER TABLE iam.setting_value ENABLE ROW LEVEL SECURITY;
ALTER TABLE iam.setting_value FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON iam.setting_value USING (tenant_id = current_setting('app.tenant_id', true)::uuid);

-- ---------------------------------------------------------------- primary department of a staff member
ALTER TABLE iam.user_role ADD COLUMN is_primary boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN iam.user_role.is_primary IS 'The grant whose scope is the user''s primary unit of its type (at most one per user and scope type); settings resolve through the primary department.';
CREATE UNIQUE INDEX uq_user_role_primary ON iam.user_role (tenant_id, user_id, scope_type) WHERE is_primary AND deleted_at IS NULL;

-- ---------------------------------------------------------------- tenant directory for sign-in
CREATE TABLE iam.tenant_directory (
    tenant_id uuid NOT NULL,
    tenant_code varchar(60) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'active',
    synced_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_tenant_directory PRIMARY KEY (tenant_id),
    CONSTRAINT uq_tenant_directory_tenant_code UNIQUE (tenant_code),
    CONSTRAINT ck_tenant_directory_status CHECK (status IN ('active', 'suspended', 'closed'))
);
COMMENT ON TABLE iam.tenant_directory IS 'Local copy of tenant codes and status, kept from platform tenant events (against-DAG, events only) so that sign-in can resolve a tenant code without reading another schema. Holds no personal data; read before a tenant is known, so it carries no row-level security.';
COMMENT ON COLUMN iam.tenant_directory.tenant_id IS 'Tenant (platform.tenant.id; logical, maintained from platform events).';
COMMENT ON COLUMN iam.tenant_directory.tenant_code IS 'Code users type at sign-in.';
COMMENT ON COLUMN iam.tenant_directory.status IS 'Only active tenants can sign in.';
COMMENT ON COLUMN iam.tenant_directory.synced_at IS 'When the row was last updated from a platform event.';

-- ---------------------------------------------------------------- progressive sign-in lockout and refresh families
ALTER TABLE iam.user_account ADD COLUMN locked_until timestamptz;
COMMENT ON COLUMN iam.user_account.locked_until IS 'Sign-in is refused until this time after repeated failures (progressive lockout); NULL = not locked out. Independent of status locked, which only an administrator lifts.';
CREATE INDEX ix_auth_token_refresh_family ON iam.auth_token (tenant_id, name) WHERE token_type = 'refresh';
COMMENT ON INDEX iam.ix_auth_token_refresh_family IS 'Refresh tokens of one sign-in session (family id in name): rotation and reuse detection revoke the whole family.';
