"""Generates each module's reference cleanup (database/logical-references.md, "Events drive cleanup"): the module
subscribes to the `<owner>.deleted` events of the records its logical references point at and applies the documented
action to its own rows — "null the column" or "archive/delete the dependent row" (a soft delete), from both tables
of that file (the forward references and the against-DAG ones). Every action text is known to the generator; an
unknown one stops it. Every changed row is
audited and announced on the module's own outbox (`<table>.updated` / `<table>.deleted`), so the cleanup cascades to
the modules that reference it in turn.

    python3 tools/backend/crud/gen_events.py

References are not checked against their owner when they are written (decision of 2026-11-07, option C): the
cleanup keeps the dependents consistent once an owner goes away. gen.py runs this too.
"""
