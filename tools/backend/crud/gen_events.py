HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.normpath(HERE + '/../../../backend')
REFS = os.path.normpath(BACKEND + '/../database/logical-references.md')
CATALOG = HERE + '/target/catalog.json'
MARK = '// GENERATED by tools/backend/crud/gen_events.py — regenerate, do not edit by hand.\n'
NULL = 'null the column'
ARCHIVE = 'archive/delete the dependent row'


def pascal(m):
    return m[0].upper() + m[1:]


def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


def const(name):
    return re.sub(r'[^A-Z0-9]+', '_', name.upper()).strip('_')


# every action text of database/logical-references.md: the cleanup it means, or None for a deliberate no-op
FORWARD_ACTIONS = {
    NULL: NULL,
    ARCHIVE: ARCHIVE,
    'owner is never hard-deleted (archived by status); no action needed': None,
}
AGAINST_DAG_ACTIONS = {
    'on owner deletion, null the column.': NULL,
    'on owner deletion, delete the row.': ARCHIVE,  # a soft delete, as every dependent row
    'on owner deletion, archive/retain (the row is evidence; it keeps the id).': None,
}


def references():
    """(column, owner, action text, section) of every row of both tables of logical-references.md."""
    section = 'forward'
    for line in open(REFS):
        if line.startswith('## Against-DAG'):
            section = 'against-dag'
        if not line.startswith('| `'):
            continue
        cells = [c.strip() for c in line.split('|')]
        if section == 'forward':
            yield cells[1].strip('`'), cells[2].strip('`'), cells[3], section
        else:
            column, owner = [p.strip().strip('`') for p in cells[1].split('→')]
            yield column, owner, cells[2], section


def actions():
    """(dependent module, table, column, owner, action) for every reference whose owner deletion needs an action;
    plus the ones that cannot be applied, with the reason. An action text the generator does not know stops it:
    no reference is skipped silently."""
    catalog = json.load(open(CATALOG))
    out, kept = [], []
    for column, owner, text, section in references():
        known = FORWARD_ACTIONS if section == 'forward' else AGAINST_DAG_ACTIONS
        if text not in known:
            raise SystemExit('logical reference %s (%s): unknown event action "%s"' % (column, section, text))
        action = known[text]
        if action is None:
            continue
        schema, table, col = column.split('.')
        t = catalog[schema + '.' + table]
        cols = {c['name']: c for c in t['cols']}
        if col not in cols or 'tenant_id' not in cols or 'id' not in cols:
            raise SystemExit('logical reference %s does not match the catalog' % column)
        if action == NULL and cols[col]['nn']:
            raise SystemExit('logical reference %s: "null the column" on a NOT NULL column' % column)
        if action == ARCHIVE and 'deleted_at' not in cols:
            kept.append((column, owner, 'append-only table without deleted_at: its rows age out with the table\'s '
                                        'partition retention instead'))
            continue
        out.append(dict(module=schema, table=table, col=col, owner=owner, action=action,
                        versioned='row_version' in cols, stamped='updated_at' in cols))
    return out, kept


def statement(a):
    sets = ['deleted_at = :now'] if a['action'] == ARCHIVE else ['%s = NULL' % a['col']]
    if a['stamped']:
        sets.append('updated_at = :now')
    if a['versioned']:
        sets.append('row_version = row_version + 1')
    if len(', '.join(sets)) > 90:
        sets = [sets[0], '\n                   ' + sets[1]] + sets[2:]
    where = 'tenant_id = :tenantId\n               AND %s = :ownerId' % a['col']
    if a['action'] == ARCHIVE:
        where += '\n               AND deleted_at IS NULL'
    return ('UPDATE %s.%s\n               SET %s\n             WHERE %s\n            RETURNING id'
            % (a['module'], a['table'], ', '.join(sets), where))


def name_of(a):
    verb = 'ARCHIVE' if a['action'] == ARCHIVE else 'CLEAR'
    return '%s_%s_%s' % (verb, const(a['table']), const(a['col']))


