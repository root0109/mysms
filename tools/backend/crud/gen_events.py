def main():
    items, kept = actions()
    by_module = {}
    for a in items:
        by_module.setdefault(a['module'], []).append(a)
    for m in sorted(by_module):
        generate(m, by_module[m])
    report = HERE + '/target/reference-cleanup.json'
    json.dump(dict(actions=[{k: v for k, v in a.items()} for a in items],
                   kept=[dict(column=c, owner=o, why=w) for c, o, w in kept]), open(report, 'w'), indent=1)
    print('reference cleanup: %d actions in %d modules, %d kept by design' % (len(items), len(by_module),
                                                                              len(kept)))


if __name__ == '__main__':
    main()
