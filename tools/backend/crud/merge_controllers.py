"""Merges the generated controller with the hand-written operations of the controllers that serve both.

A contract interface whose operations are partly generated and partly hand-written has one controller. The generator
writes its version to target/conflicts/; this script takes that version and puts back, verbatim from the current
controller, the hand-written operations listed in KEEP together with the collaborators they use. Run it after gen.py.
"""
import os
import re

import fmt

TOOLS = os.path.dirname(os.path.abspath(__file__)) + '/'
BACKEND = os.path.normpath(TOOLS + '../../../backend') + '/'

# controller -> the operations served by hand-written code (everything else comes from the generator or is a stub)
KEEP = {
    'people/src/main/java/com/mysms/people/controller/PersonController.java': ['getMyPerson', 'updateMyPerson'],
    'iam/src/main/java/com/mysms/iam/controller/UserAccountController.java': [
        'login', 'refreshToken', 'logout', 'getMe', 'listMySettings', 'setMySetting', 'resetMySetting',
        'changePassword', 'setUserCredentials', 'acceptTerms'],
}
MARK = '// GENERATED by tools/backend/crud — regenerate, do not edit by hand.\n'


def method(src, name):
    m = re.search(r'(    /\*\*(?:(?!\*/).)*\*/\n)?    @Override\n    public ResponseEntity<[^\n]*?> %s\(.*?\n    }\n' % name, src,
                  re.S)
    if not m:
        raise SystemExit('method %s not found' % name)
    return m.group(0)


def stub(src, name):
    return re.search(r'    @Override\n    public ResponseEntity<[^\n]*?> %s\(.*?\n    }\n' % name, src, re.S).group(0)


def ctor(src, cls):
    return re.search(r'    public %s\((.*?)\) \{\n(.*?)    }\n' % cls, src, re.S)


def main():
    for rel, keep in KEEP.items():
        path = BACKEND + rel
        cls = os.path.basename(rel)[:-5]
        generated_path = TOOLS + 'target/conflicts/' + cls + '.java'
        if not os.path.exists(generated_path):
            raise SystemExit('run gen.py first: ' + generated_path)
        current = open(path).read()
        out = open(generated_path).read().replace(MARK, '')
        for name in keep:
            out = out.replace(stub(out, name), method(current, name))
        # collaborators of the hand-written operations: every field of the current controller that is not a
        # generated resource service
        generated_fields = set(re.findall(r'    private final (\w+) (\w+);', out))
        fields = [f for f in re.findall(r'    private final ([\w<>]+) (\w+);', current) if f not in generated_fields
                  and not (f[0].endswith('Service') and f[1] == f[0][:1].lower() + f[0][1:])]
        c = ctor(out, cls)
        params = ', '.join('%s %s' % f for f in fields) + (', ' + c.group(1) if c.group(1).strip() else '')
        assigns = ''.join('        this.%s = %s;\n' % (f[1], f[1]) for f in fields) + c.group(2)
        annotated = {f[1]: f for f in fields}
        # keep annotations such as @Qualifier on the hand-written constructor parameters
        old = ctor(current, cls)
        for p in re.split(r',\s*(?![^()]*\))', old.group(1)):
            p = ' '.join(p.split())
            name = p.split(' ')[-1]
            if name in annotated and p != '%s %s' % annotated[name]:
                params = params.replace('%s %s' % annotated[name], p, 1)
        out = out.replace(c.group(0), '    public %s(%s) {\n%s    }\n' % (cls, params, assigns))
        field_block = ''.join('    private final %s %s;\n' % f for f in fields)
        out = re.sub(r'(public class %s implements \w+ \{\n\n)' % cls, r'\g<1>' + field_block.replace('\\', '\\\\'),
                     out, count=1)
        out = out.replace(' * answer 501 NOT_IMPLEMENTED.\n */',
                          ' * answer 501 NOT_IMPLEMENTED. Standard operations follow the generated pattern (tools/backend/crud,'
                          ' merged by\n * merge_controllers.py); %s are hand-written.\n */' % ', '.join(keep))
        imports = sorted(set(re.findall(r'^import [^;]+;$', out, re.M)) | set(re.findall(r'^import [^;]+;$', current, re.M)))
        out = re.sub(r'^import [^;]+;\n', '', out, flags=re.M)
        out = re.sub(r'(package [\w.]+;\n\n)', lambda m: m.group(1) + '\n'.join(imports) + '\n\n', out, count=1)
        out = re.sub(r'\n{3,}', '\n\n', out)
        with open(path, 'w') as f:
            f.write(fmt.format_java(out))
        print('merged', rel, '(kept %d hand-written operations, %d collaborators)' % (len(keep), len(fields)))


if __name__ == '__main__':
    main()
