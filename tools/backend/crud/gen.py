def apply_case(a, f):
    g = 'changes.get%s()' % uc(f['name'])
    if f['conv'] == 'secret':
        return 'seal%s(entity, %s)' % (uc(f['name']), g)
    s = 'entity.set%s' % uc(f['ent'])
    if f['conv'] == 'enum':
        return '%s(Optional.ofNullable(%s).map(v -> v.getValue()).orElse(null))' % (s, g)
    if f['conv'] == 'enumlist':
        return '%s(Optional.ofNullable(%s).map(l -> l.stream().map(v -> v.getValue()).toList()).orElse(null))' % (s, g)
    if f['conv'] in WIRE:
        return '%s(%s)' % (s, wire_call(f, g))
    return '%s(%s)' % (s, g)


