def analyse(r):
    mod = r['module']
    name = r['name']
    if mod in EXCLUDE_MODULES or (mod, name) in EXCLUDE:
        raise Skip('served or reserved for hand-written code')
    glob = not r['tenant']  # a global table (no tenant): platform-administered, generated in its own shape
    t = r['t']
    partition = None
    if t['partitioned']:
        pk = next(c['cols'] for c in t['cons'] if c['type'] == 'p')
        key = [c for c in pk if c != 'id']
        if len(key) != 1:
            raise Skip('partitioned table without a single partition column')
        partition = key[0]
    for c in AUDIT_COLS:
        if c not in r['cols']:
            raise Skip('missing audit column ' + c)
    dto = javasrc.model(mod, name)
    if dto is None:
        raise Skip('no generated model')
    upd = javasrc.model(mod, name + 'Update') if 'Update' in r['ops'] else None
    fields = []
    masked = []
    for f in r['fields']:
        if f['audit']:
            continue
        if f.get('virtual'):
            if f['name'] not in dto['fields']:
                raise Skip('field %s missing in model' % f['name'])
            masked.append(dict(name=f['name'], of=f['masked_of']))
            continue
        col = r['cols'][f['col']]
        base = col['base']
        if base not in TYPE:
            raise Skip('column type %s of %s' % (base, f['col']))
        if base == 'inet' and (('Create' in r['ops'] and not f.get('ro')) or (upd and f['name'] in upd['fields'])):
            raise Skip('writable inet column ' + f['col'])
        dto_type = dto['fields'].get(f['name'])
        if dto_type is None:
            raise Skip('field %s missing in model' % f['name'])
        ent_type = TYPE[base][0]
        conv = 'secret' if f.get('secret') else conversion(f, dto_type, ent_type, base, dto)
        if conv == 'secret' and (dto_type != 'String' or base != 'text'):
            raise Skip('secret %s is not text' % f['name'])
        if conv is None:
            raise Skip('conversion %s -> %s for %s' % (dto_type, base, f['name']))
        prec = None
        m = re.match(r'numeric\((\d+),(\d+)\)', col['type'])
        if m:
            prec = (int(m.group(1)), int(m.group(2)))
        elif base == 'numeric' and conv == 'decimal':
            raise Skip('unbounded numeric ' + f['col'])
        ro = bool(f.get('ro'))
        from_path = r['parent'] is not None and f['col'] == r['parent_col']
        copied = copied_from_parent(r, f['col']) if ro and not from_path else None
        if ro and not from_path and not copied and col['nn'] and col['default'] is None:
            raise Skip('read-only not-null column without default ' + f['col'])
        upd_type = upd['fields'].get(f['name']) if upd else None
        fields.append(dict(name=f['name'], col=f['col'], base=base, nn=col['nn'], has_default=col['default'] is not None,
                           dto_type=dto_type, ent_type=ent_type, conv=conv, prec=prec, ro=ro,
                           writable=upd_type is not None, upd_type=upd_type, prop=f['prop'],
                           ent=M.camel(f['col']), from_path=from_path, masked_of=f.get('masked_of'), copied=copied))
    by_col = {f['col']: f for f in fields}
    by_name = {f['name']: f for f in fields}
    for m in masked + [dict(name=f['name'], of=f['masked_of']) for f in fields if f['masked_of']]:
        if by_name.get(m['of'], {}).get('conv') != 'secret':
            raise Skip('masked %s without its secret' % m['name'])
    parent = None
    if r['parent']:
        parent = by_col[r['parent_col']]
    # methods of the controller interface
    ops = {}
    tags = set()
    for kind, o in r['ops'].items():
        sec = o['op'].get('security')
        if sec != [{'bearerAuth': []}] and not glob:
            continue  # public or platform-staff variants of tenant data need hand-written projections
        tags.add(o['tag'])
        ops[kind] = o
    if not ops:
        raise Skip('no tenant-user operation')
    if len(tags) != 1:
        raise Skip('operations under several tags')
    tag = tags.pop()
    api = javasrc.api_methods(mod, tag)
    if api is None:
        raise Skip('no Api interface')
    methods = {}
    for kind, o in ops.items():
        meth = lc(o['oid'])
        if meth not in api:
            raise Skip('method %s not in %sApi' % (meth, tag))
        ret, params, path = api[meth]
        names = [p[1] for p in params]
        if kind == 'List':
            extra = [n for n in names if n not in STANDARD_LIST_PARAMS and n != r['parent']]
            if extra:
                continue  # list with extra query parameters: hand-written
        if kind == 'Create' and [n for n in names if n not in (lc(name), 'idempotencyKey', 'validateOnly', r['parent'])]:
            continue
        if kind in ('Get', 'Update', 'Delete') and not re.search(r'\{\w+\}$', path):
            raise Skip('singleton resource (no id in %s)' % path)
        methods[kind] = dict(name=meth, ret=ret, params=params, path=path)
    if not methods:
        raise Skip('no standard method fits')
    if partition:
        names = {'created_at': 'createTime', 'updated_at': 'updateTime'}
        pf = names.get(partition) or (by_col[partition]['name'] if partition in by_col else None)
        if pf is None:
            raise Skip('partition column %s is not a contract field' % partition)
        partition = dict(col=partition, field=pf)
    scope = scoping(r, by_col)
    uniques = unique_checks(r, by_col)
    fks = fk_checks(r, by_col)
    children = child_checks(r)
    transitions = transitions_of(r, by_col)
    return dict(r=r, module=mod, name=name, table=r['table'], fields=fields, by_col=by_col, parent=parent, tag=tag,
                methods=methods, api=api, scope=scope, uniques=uniques, fks=fks, children=children, dto=dto, upd=upd,
                alias='r', transitions=transitions, masked=masked, partition=partition, glob=glob)


TRANSITIONS = json.load(open(TOOLS + 'transitions.json'))['transitions']


def transitions_of(r, by_col):
    """The state transitions of transitions.json that act on this resource, resolved against contract and schema."""
    mod = r['mod']
    out = []
    for t in TRANSITIONS:
        module, oid = t['op'].split('.', 1)
        if module != r['module']:
            continue
        found = None
        for path, item in mod.doc['paths'].items():
            for verb, op in item.items():
                if isinstance(op, dict) and op.get('operationId') == t['op']:
                    found = (path, verb, op)
        if found is None:
            raise SystemExit('transitions.json: no operation ' + t['op'])
        path, verb, op = found
        ret = op['responses'].get('200', {}).get('content', {}).get('application/json', {}).get('schema', {})
        if ret.get('$ref', '').split('/')[-1] != r['name']:
            continue
        path_params = re.findall(r'\{(\w+)\}', path)
        nested = len(path_params) == 2 and r['parent'] == path_params[0]
        if op.get('security') != [{'bearerAuth': []}] or verb != 'post' or not (len(path_params) == 1 or nested):
            raise SystemExit('transitions.json: %s is not a tenant-user POST on one row' % t['op'])
        req = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema', {})
        req_name = req.get('$ref', '').split('/')[-1]
        req_model = javasrc.model(module, req_name) if req_name else None
        req_fields = req_model['fields'] if req_model else {}
        method = lc(oid)
        api = javasrc.api_methods(module, op['tags'][0])
        if method not in api:
            raise SystemExit('transitions.json: %s not in %sApi' % (method, op['tags'][0]))
        cols = r['cols']
        for col in list(t['guard']) + list(t['set']):
            if col not in cols:
                raise SystemExit('transitions.json: %s: no column %s in %s' % (t['op'], col, r['table']))
        for col in t['guard']:
            if col not in by_col:
                raise SystemExit('transitions.json: %s: guard column %s is not in the contract' % (t['op'], col))
        for col, value in t['set'].items():
            if isinstance(value, str) and value.startswith('$param:') and value[7:] not in req_fields:
                raise SystemExit('transitions.json: %s: no request field %s' % (t['op'], value[7:]))
        if t.get('reason') and 'reason' not in req_fields:
            raise SystemExit('transitions.json: %s: no reason in the request' % t['op'])
        step = re.sub(r'%s$' % r['name'], '', oid)
        step = step[:1].lower() + step[1:] if step != oid else lc(oid)
        out.append(dict(op=t['op'], oid=oid, method=method, tag=op['tags'][0], path=path, guard=t['guard'],
                        set=t['set'], reason=bool(t.get('reason')), req=req_name, req_fields=req_fields,
                        has_etag='etag' in req_fields, nested=nested,
                        if_match=any(p[1] == 'ifMatch' for p in api[method][1]), permission=op['x-permission'], step=step,
                        params=api[method][1], description=op.get('description') or op.get('summary') or ''))
    return out


def conversion(f, dto_type, ent_type, base, dto):
    """How a DTO value becomes the entity value: 'same', 'enum', 'enumlist', 'decimal', 'int64', 'time'."""
    if dto_type == ent_type:
        return 'same'
    if ent_type == 'String' and (dto_type.endswith('Enum') or f['jt'][0] == 'enumref'):
        return 'enum'
    if ent_type == 'List<String>' and dto_type.startswith('List<') and dto_type != 'List<String>':
        return 'enumlist'
    if dto_type == 'String' and ent_type == 'BigDecimal':
        return 'decimal'
    if dto_type == 'String' and ent_type == 'Long':
        return 'int64'
    if dto_type == 'String' and ent_type == 'LocalTime':
        return 'time'
    # a protobuf-style duration ("5400s") stored as whole minutes or seconds
    if dto_type == 'String' and ent_type == 'Integer' and str(f['prop'].get('pattern', '')).endswith('s$') \
            and (f['col'].endswith('_minutes') or f['col'].endswith('_seconds')):
        return 'duration'
    return None


WIRE = ('decimal', 'int64', 'time', 'duration')


def wire_call(f, expr):
    """The WireValues conversion of one value (either direction: overloads pick it)."""
    if f['conv'] == 'duration':
        return 'WireValues.duration(%s, %d)' % (expr, 60 if f['col'].endswith('_minutes') else 1)
    return 'WireValues.%s(%s)' % (f['conv'], expr)


def copied_from_parent(r, col):
    """The parent column a read-only column copies, when a composite FK (parent id, col) → parent (id, column) keeps
    them in step (attendance_record.attendance_date copies its sheet's date): the insert reads it from the parent."""
    if r['parent'] is None:
        return None
    for c in M.CATALOG[r['table']]['cons'] or []:
        if c['type'] == 'f' and sorted(c['cols']) == sorted([r['parent_col'], col]) and c['refcols'][
                c['cols'].index(r['parent_col'])] == 'id':
            return dict(table=c['ref'], col=c['refcols'][c['cols'].index(col)])
    return None


def fk_cons(table):
    out = []
    for c in M.CATALOG[table]['cons'] or []:
        if c['type'] != 'f':
            continue
        cols = [x for x in c['cols'] if x != 'tenant_id']
        refcols = [x for x in c['refcols'] if x != 'tenant_id']
        if len(cols) != 1 or refcols != ['id']:
            continue
        out.append(dict(col=cols[0], ref=c['ref'], name=c['name'], ondelete=c['ondelete']))
    return out


def scoping(r, by_col):
    """('direct', nullable) | ('chain', [(col, table)...], nullable) | ('self',) | ('tenant',)."""
    if r['table'] == 'org.institution':
        return ('self',)
    if 'institution_id' in by_col:
        return ('direct', not by_col['institution_id']['nn'])
    # breadth-first over in-schema foreign keys to a table that carries institution_id
    start = r['table']
    queue = collections.deque([(start, [])])
    seen = {start}
    best = None
    while queue:
        table, path = queue.popleft()
        if len(path) >= 3:
            continue
        for fk in fk_cons(table):
            ref = fk['ref']
            if ref in seen or ref.split('.')[0] != start.split('.')[0]:
                continue
            col_nn = next(c['nn'] for c in M.CATALOG[table]['cols'] if c['name'] == fk['col'])
            if not path and fk['col'] not in by_col:
                continue
            step = path + [(fk['col'], ref, col_nn)]
            ref_cols = {c['name']: c for c in M.CATALOG[ref]['cols']}
            if 'institution_id' in ref_cols:
                cand = (all(s[2] for s in step), len(step), step, not ref_cols['institution_id']['nn'])
                if best is None or (cand[0], -cand[1]) > (best[0], -best[1]):
                    best = cand
                continue
            seen.add(ref)
            queue.append((ref, step))
    if best is None:
        return ('tenant',)
    nullable = (not best[0]) or best[3]
    return ('chain', [(s[0], s[1]) for s in best[2]], nullable)


def unique_checks(r, by_col):
    t = M.CATALOG[r['table']]
    out = []
    candidates = []
    for c in t['cons'] or []:
        if c['type'] == 'u':
            candidates.append((c['name'], c['cols'], None, 'NULLS NOT DISTINCT' in c['def']))
    for i in t['uidx'] or []:
        candidates.append((i['name'], i['cols'], i['pred'], 'NULLS NOT DISTINCT' in i['def']))
    for name, cols, pred, nnd in candidates:
        if 'id' in cols or None in cols:
            continue
        cols = [c for c in cols if c != 'tenant_id']
        if not cols or any(c not in by_col for c in cols):
            continue
        if pred and re.sub(r'[()\s]', '', pred) != 'deleted_atISNULL':
            # a partial index on other conditions (is_current, status, effective_to IS NULL...) only conflicts when
            # the candidate row is in the index too; the index itself answers 409 (DuplicateKeyException) then
            continue
        out.append(dict(name=name, cols=cols, pred=pred, nnd=nnd))
    return sorted(out, key=lambda u: u['name'])  # stable output whatever order the catalog lists the indexes in


def fk_checks(r, by_col):
    out = []
    for fk in fk_cons(r['table']):
        if fk['col'] not in by_col or fk['ref'].split('.')[0] != r['module']:
            continue
        ref_cols = {c['name'] for c in M.CATALOG[fk['ref']]['cols']}
        out.append(dict(col=fk['col'], ref=fk['ref'], soft='deleted_at' in ref_cols))
    return sorted(out, key=lambda f: f["col"])


# rows that belong to the referenced row and are retired together with it by its Rules#afterDelete, so they never
# block the delete (sign-in sessions, refresh tokens, devices and preferences of a deleted account)
OWNED_CHILDREN = {('iam.user_account', 'iam.auth_token'), ('iam.user_account', 'iam.user_session'),
                  ('iam.user_account', 'iam.user_device'), ('iam.user_account', 'iam.user_preference')}


def child_checks(r):
    out = []
    for table, info in M.CATALOG.items():
        if table.split('.')[0] != r['module']:
            continue
        for fk in fk_cons(table):
            if fk['ref'] == r['table'] and (r['table'], table) not in OWNED_CHILDREN:
                cols = {c['name'] for c in info['cols']}
                if not r['tenant'] and 'tenant_id' in cols:
                    # a global row is changed in a transaction that binds no tenant, which sees no tenant's rows:
                    # tenants keep their reference to the retired (soft-deleted) row, as with any other reference
                    continue
                out.append(dict(table=table, col=fk['col'], soft='deleted_at' in cols, partitioned=info['partitioned']))
    return sorted(out, key=lambda c: (c["table"], c["col"]))


