def to_dto_expr(f):
    g = 'entity.get%s()' % uc(f['ent'])
    if f['conv'] == 'enum':
        return '%s == null ? null : %s.fromValue(%s)' % (g, enum_class(f, f['dto_type'], dto_owner=True), g)
    if f['conv'] == 'enumlist':
        inner = re.match(r'List<(.+)>', f['dto_type']).group(1)
        return '%s == null ? null : %s.stream().map(%s::fromValue).toList()' % (g, g, inner)
    if f['conv'] in WIRE:
        return wire_call(f, g)
    return None


def enum_class(f, typ, dto_owner):
    return typ if '.' in typ or not typ.endswith('Enum') else ('%s.%s' % (f['owner'], typ))


