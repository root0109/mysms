def imports(lines):
    std = sorted(set(l for l in lines if l))
    return '\n'.join('import %s;' % l for l in std)


def entity_src(a):
    mod, name = a['module'], a['name']
    used = {'com.mysms.core.entity.BaseEntity', 'lombok.EqualsAndHashCode', 'lombok.Getter', 'lombok.NoArgsConstructor',
            'lombok.Setter', 'lombok.experimental.SuperBuilder', 'java.util.UUID'}
    body = []
    for f in a['fields']:
        t = f['ent_type']
        used |= java_imports(t)
        body.append('    private %s %s;' % (t, f['ent']))
    return MARK + '''package {p}.domain;

{imports}

/** A row of {table} (column for column; the audit set comes from {{@link BaseEntity}}). */
@Getter
@Setter
@SuperBuilder
@NoArgsConstructor
@EqualsAndHashCode(callSuper = true, onlyExplicitlyIncluded = true)
public class {n}Entity extends BaseEntity {{

    public static final String TABLE = "{table}";
{tenant}{body}
}}
'''.format(p=pkg(mod), imports=imports(used), table=a['table'], n=name, body='\n'.join(body),
           tenant='' if a['glob'] else '\n    private UUID tenantId;\n')


def java_imports(t):
    out = set()
    for simple, full in (('UUID', 'java.util.UUID'), ('BigDecimal', 'java.math.BigDecimal'),
                         ('LocalDate', 'java.time.LocalDate'), ('OffsetDateTime', 'java.time.OffsetDateTime'),
                         ('LocalTime', 'java.time.LocalTime'), ('List', 'java.util.List')):
        if re.search(r'\b%s\b' % simple, t):
            out.add(full)
    return out


def scope_sql(a, alias):
    """SQL predicate (bound with :scopeAll, :scopeIds) restricting rows to the caller's institutions."""
    s = a['scope']
    if s[0] == 'tenant':
        return None
    if s[0] == 'self':
        return '(:scopeAll OR %s.id = ANY(:scopeIds))' % alias
    if s[0] == 'direct':
        null = (' OR %s.institution_id IS NULL' % alias) if s[1] else ''
        return '(:scopeAll OR %s.institution_id = ANY(:scopeIds)%s)' % (alias, null)
    chain = s[1]
    # innermost: the table with institution_id
    inner = None
    for depth in range(len(chain) - 1, -1, -1):
        col, ref = chain[depth]
        a2 = 'p%d' % depth
        ref_cols = {c['name']: c for c in M.CATALOG[ref]['cols']}
        if inner is None:
            null = (' OR %s.institution_id IS NULL' % a2) if not ref_cols['institution_id']['nn'] else ''
            cond = '(%s.institution_id = ANY(:scopeIds)%s)' % (a2, null)
        else:
            nxt_col = chain[depth + 1][0]
            nxt_nn = next(c['nn'] for c in M.CATALOG[ref]['cols'] if c['name'] == nxt_col)
            null = ('%s.%s IS NULL OR ' % (a2, nxt_col)) if not nxt_nn else ''
            cond = '(%s%s.%s IN (%s))' % (null, a2, nxt_col, inner)
        inner = 'SELECT %s.id FROM %s %s WHERE %s' % (a2, ref, a2, cond)
    first_col = chain[0][0]
    null = (' OR %s.%s IS NULL' % (alias, first_col)) if not a['by_col'][first_col]['nn'] else ''
    return '(:scopeAll OR %s.%s IN (%s)%s)' % (alias, first_col, inner, null)


def chain_lookup_sql(a):
    """SELECT institution_id reached from the first chain column's value :ref (empty: tenant-level)."""
    chain = a['scope'][1]
    sql_from = []
    for depth, (col, ref) in enumerate(chain):
        sql_from.append((col, ref, 'p%d' % depth))
    last = sql_from[-1][2]
    joins = 'FROM %s p0' % sql_from[0][1]
    for depth in range(1, len(sql_from)):
        col, ref, al = sql_from[depth]
        joins += ' JOIN %s %s ON %s.id = %s.%s' % (ref, al, al, sql_from[depth - 1][2], col)
    return 'SELECT %s.institution_id %s WHERE p0.id = :ref' % (last, joins)


def bind_expr(f, var='e'):
    return '%s.get%s()' % (var, uc(f['ent']))


def bind_value(f, var='e'):
    g = bind_expr(f, var)
    if f['ent_type'] == 'List<String>':
        return '%s == null ? null : %s.toArray(String[]::new)' % (g, g)
    return g


def repository_src(a):
    mod, name, table = a['module'], a['name'], a['table']
    al = a['alias']
    M_ = module_class(mod)
