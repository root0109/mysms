def pkg(mod):
    return 'com.mysms.' + mod


def write(path, text):
    text = fmt.format_java(text)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        old = open(path).read()
        if not old.startswith(MARK) and 'GENERATED by tools/backend/crud' not in old and 'GENERATED by tools/backend/crud' not in old:
            conflict = WORK + 'conflicts/' + os.path.basename(path)
            os.makedirs(os.path.dirname(conflict), exist_ok=True)
            open(conflict, 'w').write(text)
            print('hand-written file kept; generated version in', conflict)
            return
        if old == text:
            return
    with open(path, 'w') as f:
        f.write(text)


