def wire_check(a, var, creatable):
    """64-bit integers and times of day travel as strings: refuse unparsable ones with 422 before mapping."""
    checks = []
    for f in a['fields']:
        if f['conv'] not in ('int64', 'time', 'duration') or (f['ro'] and not f['from_path']):
            continue
        if not creatable and not f['writable']:
            continue
        if f['conv'] == 'duration':
            checks.append('        WireValues.checkDuration("%s", %s.get%s(), %d, wire);' % (
                f['name'], var, uc(f['name']), 60 if f['col'].endswith('_minutes') else 1))
            continue
        kind = 'Int64' if f['conv'] == 'int64' else 'Time'
        checks.append('        WireValues.check%s("%s", %s.get%s(), wire);' % (kind, f['name'], var, uc(f['name'])))
    if not checks:
        return ''
    return ('\n        List<FieldError> wire = new ArrayList<>();\n' + '\n'.join(checks)
            + '\n        if (!wire.isEmpty()) {\n            throw new ValidationFailedException(wire);\n        }')


def parent_visible(a):
    """A nested create under a parent the caller cannot see answers 404, exactly like reading it."""
    parent = a['parent']
    if not parent:
        return ''
    fk = next((f for f in a['fks'] if f['col'] == parent['col']), None)
    lines = []
    if fk:
        lines.append('''
            if (!repository.%s(entity.get%s())) {
                throw new ResourceNotFoundException("%s", entity.get%s());
            }''' % (fk_method(fk), uc(parent['ent']), fk['ref'], uc(parent['ent'])))
    if a['scope'][0] == 'chain' and a['scope'][1][0][0] == parent['col']:
        lines.append('''
            if (!scope.canRead(institutionOf(entity))) {
                throw new ResourceNotFoundException("%s", entity.get%s());
            }''' % (a['scope'][1][0][1], uc(parent['ent'])))
    return ''.join(lines)


def human(pascal):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', pascal).lower()


