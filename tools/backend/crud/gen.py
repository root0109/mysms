def controller_src(mod, tag, api, served):
    """served: {methodName: (resource analysis, kind)}."""
    M_ = module_class(mod)
    imp = {'org.springframework.http.ResponseEntity', 'org.springframework.web.bind.annotation.RestController',
           'com.mysms.contracts.%s.api.%sApi' % (mod, tag)}
    services = {}
    methods = []
    for meth in sorted(api):
        ret, params, path = api[meth]
        for t, _ in params:
            add_type_imports(imp, mod, t)
        add_type_imports(imp, mod, ret)
        sig = ', '.join('%s %s' % (t, nme) for t, nme in params)
        head = '    @Override\n    public ResponseEntity<%s> %s(%s) {' % (ret, meth, sig)
        head = wrap_signature(head)
        if meth not in served:
            imp.add('com.mysms.core.error.NotImplementedException')
            methods.append(head + '\n        throw new NotImplementedException();\n    }\n')
            continue
        a, kind = served[meth]
        svc = lc(a['name']) + 'Service'
        services[svc] = a['name'] + 'Service'
        imp.add('%s.business.%sService' % (pkg(mod), a['name']))
        names = [p[1] for p in params]
        parent = a['parent']
        pa = (a['r']['parent'] + ', ') if parent else ''
        if kind.startswith('Transition:'):
            t = next(x for x in a['transitions'] if x['method'] == meth)
            body_param = next((', ' + p[1] for p in params if p[0] == t['req']), '')
            body = '''        {n} changed = {svc}.{m}({pa}{id}{b});
        return ResponseEntity.ok().eTag(changed.getEtag()).body(changed);'''.format(
                n=a['name'], svc=svc, m=meth, pa=pa if t['nested'] else '',
                id=next(p[1] for p in params if p[0] == 'UUID' and p[1] != a['r']['parent'])
                + (', ifMatch' if t['if_match'] else ''), b=body_param)
            methods.append(head + '\n' + body + '\n    }\n')
            continue
        if kind == 'List':
            imp.add('com.mysms.core.web.ReadMask')
            body = '''        {ret} list = {svc}.list{n}s({pa}pageSize, pageToken, filter, orderBy);
        list.getItems().forEach(item -> ReadMask.apply(item, fields));
        return ResponseEntity.ok(list);'''.format(ret=ret, svc=svc, n=a['name'], pa=pa)
        elif kind == 'Get':
            imp.add('com.mysms.core.web.ReadMask')
            idp = names[-2]
            body = '''        {n} found = {svc}.get{n}({pa}{id});
        return ResponseEntity.ok().eTag(found.getEtag()).body(ReadMask.apply(found, fields));'''.format(
                n=a['name'], svc=svc, pa=pa, id=idp)
        elif kind == 'Create':
            imp.add('java.net.URI')
            getpath = a['methods'].get('Get', {}).get('path')
            bodyname = lc(a['name'])
            if getpath:
                loc = '"%s"' % getpath
                loc_expr = loc
                for p in re.findall(r'\{(\w+)\}', getpath):
                    if parent and p == a['r']['parent']:
                        loc_expr = loc_expr.replace('{%s}' % p, '" + %s + "' % p)
                    else:
                        loc_expr = loc_expr.replace('{%s}' % p, '" + created.getId() + "')
                loc_expr = loc_expr.replace(' + ""', '')
                created_resp = 'ResponseEntity.created(URI.create(%s)).eTag(created.getEtag()).body(created)' % loc_expr
            else:
                created_resp = 'ResponseEntity.status(org.springframework.http.HttpStatus.CREATED).eTag(created.getEtag())' \
                               '.body(created)'
            body = '''        boolean dryRun = Boolean.TRUE.equals(validateOnly);
        {n} created = {svc}.create{n}({pa}{b}, dryRun);
        if (dryRun) {{
            return ResponseEntity.ok(created);
        }}
        return {resp};'''.format(n=a['name'], svc=svc, pa=pa, b=bodyname, resp=created_resp)
        elif kind == 'Update':
            idp = names[1] if parent else names[0]
            body = '''        {n} updated = {svc}.update{n}({pa}{id}, ifMatch, {b}, updateMask, Boolean.TRUE.equals(validateOnly));
        return ResponseEntity.ok().eTag(updated.getEtag()).body(updated);'''.format(
                n=a['name'], svc=svc, pa=pa, id=idp, b=names[2] if parent else names[2 - 1 + 1])
            # parameter order: [parent], id, ifMatch, body, updateMask, validateOnly
            order = names
            bodyp = order[order.index('ifMatch') + 1]
            body = '''        {n} updated = {svc}.update{n}({pa}{id}, ifMatch, {b}, updateMask,
                Boolean.TRUE.equals(validateOnly));
        return ResponseEntity.ok().eTag(updated.getEtag()).body(updated);'''.format(
                n=a['name'], svc=svc, pa=pa, id=order[order.index('ifMatch') - 1], b=bodyp)
        else:  # Delete
            body = '''        {svc}.delete{n}({pa}{id}, ifMatch);
        return ResponseEntity.noContent().build();'''.format(n=a['name'], svc=svc, pa=pa,
                                                               id=names[names.index('ifMatch') - 1])
        methods.append(head + '\n' + body + '\n    }\n')
    fields = '\n'.join('    private final %s %s;' % (t, nme) for nme, t in sorted(services.items()))
    ctor_params = ', '.join('%s %s' % (t, nme) for nme, t in sorted(services.items()))
    ctor_body = '\n'.join('        this.%s = %s;' % (nme, nme) for nme in sorted(services))
    ctor = wrap_signature('    public %sController(%s) {' % (tag, ctor_params))
    return MARK + '''package {p}.controller;

{imports}

/**
 * REST edge of the {tag} operations: implements the generated contract interface, so paths, parameters and payloads
 * cannot drift from api/openapi/{mod}.yaml (JAVA-CODING-RULES §9). Thin: delegate, then shape the HTTP response.
 * Authentication and the x-permission check already happened in the auth-client filter; operations not served yet
 * answer 501 NOT_IMPLEMENTED.
 */
@RestController
public class {tag}Controller implements {tag}Api {{

{fields}

{ctor}
{ctor_body}
    }}

{methods}}}
'''.format(p=pkg(mod), imports=imports(imp), tag=tag, mod=mod, fields=fields, ctor=ctor, ctor_body=ctor_body,
           methods='\n'.join(methods))


def wrap_signature(head):
    if len(head) <= 120:
        return head
    # break after the opening parenthesis at a comma
    idx = head.index('(')
    prefix = head[:idx + 1]
    rest = head[idx + 1:]
    parts = rest.split(', ')
    lines = [prefix]
    cur = prefix
    out = []
    for i, part in enumerate(parts):
        piece = part + (', ' if i < len(parts) - 1 else '')
        if len(cur) + len(piece.rstrip()) > 120:
            out.append(cur.rstrip())
            cur = ' ' * 12 + piece
        else:
            cur += piece
    out.append(cur.rstrip())
    return '\n'.join(out)


