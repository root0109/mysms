def sql_value(col, value):
    """The SQL of one assignment of a transition: a constant from transitions.json or a bind parameter."""
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if value == '$now':
        return ':now'
    if value == '$today':
        return ':today'
    if value == '$actor':
        return ':actor'
    if value.startswith('$param:'):
        return ':p' + uc(value[7:])
    if not re.match(r'^[a-z_]+$', value):
        raise SystemExit('transitions.json: unsafe constant %r for %s' % (value, col))
    return "'%s'" % value


def transition_const(t):
    return 'TRANSITION_' + plural_upper(t['oid'])


def transition_repository(a):
    """Constant UPDATE statements and methods of the resource's transitions."""
    consts = []
    methods = []
    for t in a['transitions']:
        sets = ['%s = %s' % (c, sql_value(c, v)) for c, v in t['set'].items()]
        sets += ['updated_at = :now', 'updated_by = :actor', 'row_version = row_version + 1']
        consts.append('''
    /** {op}: {guard}. */
    private static final String {const} = """
            UPDATE {table}
               SET {sets}
             WHERE id = :id AND row_version = :expected AND deleted_at IS NULL
            """;
'''.format(op=t['op'], guard=guard_text(t), const=transition_const(t), table=a['table'],
           sets=',\n                   '.join(sets)))
        params = ['UUID id', 'int expected', 'OffsetDateTime now', 'UUID actor']
        binds = ['.param("id", id)', '.param("expected", expected)', '.param("now", now)', '.param("actor", actor)']
        if '$today' in t['set'].values():
            params.append('LocalDate today')
            binds.append('.param("today", today)')
        for c, v in t['set'].items():
            if isinstance(v, str) and v.startswith('$param:'):
                name = v[7:]
                params.append('%s %s' % (t['req_fields'][name], name))
                binds.append('.param("p%s", %s)' % (uc(name), name))
        methods.append('''
    /** {op}; 0 rows means the row changed (or vanished) since it was read. */
    public int {m}({params}) {{
        return jdbc.sql({const}){binds}.update();
    }}
'''.format(op=t['op'], m=t['method'], params=', '.join(params), const=transition_const(t),
           binds=''.join('\n                ' + b for b in binds)))
    return ''.join(consts), ''.join(methods)


def guard_text(t):
    if not t['guard']:
        return 'allowed in every state'
    return 'allowed while ' + ' and '.join('%s is %s' % (c, ' or '.join(str(v).lower() for v in vs))
                                           for c, vs in t['guard'].items())


def guard_expr(a, t):
    parts = []
    for col, values in t['guard'].items():
        g = 'entity.get%s()' % uc(a['by_col'][col]['ent'])
        if all(isinstance(v, bool) for v in values):
            if values == [True]:
                parts.append('Boolean.TRUE.equals(%s)' % g)
            elif values == [False]:
                parts.append('!Boolean.TRUE.equals(%s)' % g)
            else:
                parts.append('true')
        else:
            parts.append('Set.of(%s).contains(%s)' % (', '.join('"%s"' % v for v in values), g))
    return ' && '.join(parts) if parts else 'true'


def transition_service(a):
    out = []
    n = a['name']
    for t in a['transitions']:
        req = 'request == null ? null : request.get%s()'
        args = ['now', 'Actor.current().orElse(null)']
        if '$today' in t['set'].values():
            args.append('now.toLocalDate()')
        for c, v in t['set'].items():
            if isinstance(v, str) and v.startswith('$param:'):
                args.append(req % uc(v[7:]))
        etag = ''
        if t['has_etag']:
            etag = '''
            OptionalInt expected = Etags.bodyVersion(%s);
            if (expected.isPresent() && expected.getAsInt() != entity.getRowVersion()) {
                throw new PreconditionFailedException("The etag does not match the current version.");
            }''' % (req % 'Etag')
        reason = (req % 'Reason') if t['reason'] else 'null'
        changed = ', '.join('"%s"' % (a['by_col'][c]['name'] if c in a['by_col'] else M.camel(c)) for c in t['set'])
        sig = ('UUID id, %s request' % t['req']) if t['req'] else 'UUID id'
        if t['if_match']:
            sig = sig.replace('UUID id', 'UUID id, String ifMatch')
            etag += '''
            if (entity.getRowVersion() != Etags.expectedVersion(ifMatch)) {
                throw new PreconditionFailedException("If-Match does not match the current ETag.");
            }'''
        pcheck = ''
        if t['nested']:
            pent = a['parent']['ent']
            sig = 'UUID %s, %s' % (pent, sig)
            pcheck = ' || !%s.equals(entity.get%s())' % (pent, uc(pent))
        gexpr = guard_expr(a, t)
        guard_block = '' if gexpr == 'true' else '''
            if (!(%s)) {
                throw new InvalidStateException("The %s cannot be changed this way in its current state.");
            }''' % (gexpr, human(n))
        out.append('''
    /**
     * {op}: {desc} The row must be visible and writable for the caller, and the step is {guard}; in any other state
     * the answer is 409 and nothing changes.
     */
    public {n} {m}({sig}) {{
        DataScope scope = DataScope.current({perm});
        return database.tx().write(() -> {{
            {n}Entity entity = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException(AGGREGATE, id));
            if (!scope.canRead(institutionOf(entity)){pcheck}) {{
                throw new ResourceNotFoundException(AGGREGATE, id);
            }}
            scope.requireWritable(institutionOf(entity));{etag}{guard_block}
            OffsetDateTime now = OffsetDateTime.now(clock).withOffsetSameInstant(ZoneOffset.UTC)
                    .truncatedTo(ChronoUnit.MICROS);
            if (repository.{m}(id, entity.getRowVersion(), {args}) == 0) {{
                throw new PreconditionFailedException("The row changed since it was read.");
            }}
            audit.recordTransition(AGGREGATE, id, "{step}", List.of({changed}), {reason});
            outbox.publish(AGGREGATE + ".{step}", AGGREGATE, id, {M}Events.payload(id));
            return mapper.toDto(repository.findById(id).orElseThrow(() -> new ResourceNotFoundException(AGGREGATE, id)));
        }});
    }}
'''.format(op=t['op'], desc=t['description'].strip().rstrip('.') + '.', guard=guard_text(t), n=n, m=t['method'],
           sig=sig, perm=transition_perm_const(t), etag=etag, guard_block=guard_block, pcheck=pcheck,
           args=', '.join(args), step=t['step'], changed=changed, reason=reason, M=module_class(a['module'])))
    return ''.join(out)


