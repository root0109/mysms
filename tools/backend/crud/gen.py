def write_state_machines(analysed):
    """api/state-machines.md: every generated state transition, per resource, from transitions.json."""
    lines = ['# State machines', '',
             'Generated by `tools/backend/crud/gen.py` from `tools/backend/crud/transitions.json`; do not edit by hand.',
             '', 'Each step below is served as a generated operation. The caller needs the operation\'s permission and',
             'must be able to write the row (its institution, or a tenant-wide grant for a tenant-level row). The row',
             'must be in one of the listed states, otherwise the answer is **409 `INVALID_STATE_TRANSITION`** and',
             'nothing changes. A body `etag` that does not match the row is **412**; where the operation declares',
             '`If-Match`, it is required (**428**) and must match (**412**). Each step writes an audit',
             'record (with the reason, when the request carries one) and a `<resource>.<step>` event to the module',
             'outbox, in the same transaction.', '',
             'Steps that have further effects are hand-written work and are not listed here. Examples are',
             'notifications, approval records, balances, enrolment and grading. Until they are built they answer 501.',
             '', '`$now` is the time of the step, `$today` its UTC date, `$actor` the calling user, and',
             '`$param:x` the request field `x`.']
    for a in sorted(analysed, key=lambda x: (x['module'], x['name'])):
        if not a['transitions']:
            continue
        lines += ['', '## %s.%s (`%s`)' % (a['module'], a['name'], a['table']), '',
                  '| Operation | Allowed from | Sets | Reason kept |', '|---|---|---|---|']
        for t in a['transitions']:
            guard = '; '.join('`%s` ∈ {%s}' % (c, ', '.join(json.dumps(v) for v in vs))
                              for c, vs in t['guard'].items()) or 'any state'
            sets = ', '.join('`%s` = %s' % (c, json.dumps(v) if not (isinstance(v, str) and v.startswith('$'))
                                            else '`%s`' % v) for c, v in t['set'].items())
            lines.append('| `%s` | %s | %s | %s |' % (t['op'], guard, sets, 'yes' if t['reason'] else 'no'))
    with open(os.path.normpath(ROOT + '../api/state-machines.md'), 'w') as out:
        out.write('\n'.join(lines) + '\n')


def main():
    resources, skipped = M.build()
    analysed = []
    report = collections.defaultdict(list)
    for r in resources:
        try:
            analysed.append(analyse(r))
        except Skip as e:
            report[r['module']].append((r['name'], str(e)))
    for mod, name, why in skipped:
        report[mod].append((name, why))
    by_tag = collections.defaultdict(dict)
    files = {}
    for a in analysed:
        mod = a['module']
        base = ROOT + mod + '/src/main/java/com/mysms/' + mod + '/'
        files[base + 'domain/%sEntity.java' % a['name']] = entity_src(a)
        files[base + 'repository/%sRepository.java' % a['name']] = repository_src(a)
        mapper = mapper_src(a)
        service = service_src(a)
        if a['glob']:
            mapper = mapper.replace('    @Mapping(target = "tenantId", ignore = true)\n', '')
            service = globalize_service(a, service)
        files[base + 'mapper/%sMapper.java' % a['name']] = mapper
        files[base + 'business/%sService.java' % a['name']] = service
        for kind, m in a['methods'].items():
            by_tag[(mod, a['tag'])][m['name']] = (a, kind)
        for t in a['transitions']:
            by_tag[(mod, t['tag'])][t['method']] = (a, 'Transition:' + t['op'])
    landed = {t['op'] for a in analysed for t in a['transitions']}
    missing = [t['op'] for t in TRANSITIONS if t['op'] not in landed]
    if missing:
        raise SystemExit('transitions.json: no generated resource serves ' + ', '.join(missing))
    mods = sorted({a['module'] for a in analysed})
    for mod in mods:
        files.update(module_glue(mod))
    for (mod, tag), served in sorted(by_tag.items()):
        api = javasrc.api_methods(mod, tag)
        path = ROOT + mod + '/src/main/java/com/mysms/' + mod + '/controller/%sController.java' % tag
        files[path] = controller_src(mod, tag, api, served)
    # tests: the data-driven contract test and the 501-stub count per module
    stub_counts = collections.defaultdict(dict)
    for (mod, tag), served in by_tag.items():
        api = javasrc.api_methods(mod, tag)
        import merge_controllers
        extra = len(merge_controllers.KEEP.get('%s/src/main/java/com/mysms/%s/controller/%sController.java'
                                               % (mod, mod, tag), []))
        stub_counts[mod][tag] = len(api) - len(served) - extra
    for mod in mods:
        files.update(module_tests(mod, stub_counts[mod]))
    gen_operations.main()
    gen_events.main()
    only = sys.argv[1:] if len(sys.argv) > 1 else None
    written = 0
    for path, text in sorted(files.items()):
        mod = path[len(ROOT):].split('/')[0]
        if only and mod not in only:
            continue
        write(path, text)
        written += 1
    json.dump({m: v for m, v in report.items()}, open(WORK + 'report.json', 'w'), indent=1)
    spec = []
    for a in analysed:
        spec.append(dict(module=a['module'], name=a['name'], table=a['table'], tag=a['tag'],
                         methods={k: dict(name=m['name'], path=m['path']) for k, m in a['methods'].items()},
                         parent=a['parent']['name'] if a['parent'] else None,
                         scope='global' if a['glob'] else a['scope'][0]))
    json.dump(spec, open(WORK + 'served.json', 'w'), indent=1)
    # the contract-level fact the clients build their generic record screens from (clients/packages/core)
    published = []
    for a in sorted(analysed, key=lambda x: (x['module'], x['name'])):
        published.append(collections.OrderedDict(
            module=a['module'], resource=a['name'], parent=a['r']['parent'],
            scope='global' if a['glob'] else a['scope'][0],
            operations={k: a['module'] + '.' + uc(m['name']) for k, m in sorted(a['methods'].items())},
            # partitioned tables: the field every list must bound on both sides
            partition=a['partition']['field'] if a['partition'] else None,
            # switches start where the database would put an omitted value
            booleanDefaults={f['name']: a['r']['cols'][f['col']]['default'] == 'true' for f in a['fields']
                             if f['base'] == 'bool' and a['r']['cols'][f['col']]['default'] in ('true', 'false')},
            # the generated state transitions: the step, and the field values the row must have for it
            transitions=[collections.OrderedDict(
                operation=t['op'], step=t['step'],
                guard={a['by_col'][c]['name']: vs for c, vs in t['guard'].items()}) for t in a['transitions']]))
    write_state_machines(analysed)
    with open(os.path.normpath(ROOT + '../api/standard-resources.json'), 'w') as out:
        json.dump({'description': 'Resources whose standard operations are served (generated by tools/backend/crud).',
                   'resources': published}, out, indent=1)
        out.write('\n')
    print('analysed', len(analysed), 'ops', sum(len(a['methods']) for a in analysed), 'files', written)
    print('skipped by reason:')
    c = collections.Counter(re.sub(r' [\w.]+$', '', w) for v in report.values() for _, w in v)
    for k, v in c.most_common(30):
        print('  ', v, k)


if __name__ == '__main__':
    main()
