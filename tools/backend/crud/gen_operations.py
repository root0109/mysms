"""Generates each module's OperationService surface (GetOperation, ListOperations, CancelOperation) over its own
`<module>.operation` table (api/README "Asynchronous operations", JAVA-CODING-RULES §15 O1): one concrete entity,
repository, mapper, service and controller per module that declares the operations in its contract.

    python3 tools/backend/crud/gen_operations.py

Who sees what: a caller sees the operations they started; holding the module's operation permission tenant-wide
shows every operation of the tenant. Cancelling needs the cancel permission on the same terms and is allowed while
the operation is running (the schema has no queued state; else 409); the worker, when it next checks, stops.
gen.py runs this too.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tenant_sql  # noqa: E402

BACKEND = os.path.normpath(os.path.dirname(os.path.abspath(__file__)) + '/../../../backend')
API = os.path.normpath(BACKEND + '/../api/openapi')
MARK = '// GENERATED by tools/backend/crud/gen_operations.py — regenerate, do not edit by hand.\n'


def pascal(m):
    return m[0].upper() + m[1:]


def modules():
    out = []
    for path in sorted(glob.glob(API + '/*.yaml')):
        m = os.path.basename(path)[:-5]
        text = open(path).read()
        if 'operationId: %s.GetOperation' % m in text and 'operationId: %s.CancelOperation' % m in text \
                and 'operationId: %s.ListOperations' % m in text:
            out.append(m)
    return out


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


