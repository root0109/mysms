"""Adds the explicit tenant predicate (tenant_sql.py) to hand-written repositories. Run after changing their SQL:
    python3 tools/backend/crud/apply_tenant_sql.py
Global-table repositories and the tenant directory (read before a tenant is known) are left alone; it prints the
files it changed. Idempotent."""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tenant_sql  # noqa: E402

BACKEND = os.path.normpath(os.path.dirname(os.path.abspath(__file__)) + '/../../../backend')
SKIP = {'TenantDirectoryRepository.java'}


def main():
    tables = tenant_sql.tenant_tables() - {'iam.tenant_directory'}
    for path in sorted(glob.glob(BACKEND + '/*/src/main/java/com/mysms/*/repository/*.java')):
        src = open(path).read()
        if 'GENERATED by tools/backend/crud' in src or os.path.basename(path) in SKIP:
            continue
        out = tenant_sql.rewrite_java(src, tables)
        if out != src:
            open(path, 'w').write(out)
            print('tenant predicate added:', os.path.relpath(path, BACKEND))


if __name__ == '__main__':
    main()
