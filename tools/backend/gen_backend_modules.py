def cap(m): return m[0].upper() + m[1:]

def write(path, text, overwrite=True):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    if os.path.exists(full) and (not overwrite or 'GENERATED by' not in open(full).read()):
        return  # a file without the generated mark has been taken over by hand: never overwrite it
    with open(full, 'w', encoding='utf-8') as f:
        f.write(text)

