def database_config(m):
    tenant = 'false' if m == 'master' else 'true'
    note = ('master holds global reference data: no tenant column, so transactions bind no tenant'
            if m == 'master' else 'every transaction binds the caller\'s tenant for row-level security')
    return f"""package com.mysms.{m}.config;

import com.mysms.core.db.ModuleDatabase;
import com.mysms.core.db.ModuleDatabaseHealthIndicator;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.env.Environment;

/**
 * The module's own database: pool, transaction manager, executor and Flyway history for schema "{m}" only,
 * bound from mysms.{m}.datasource.* ({note}).
 */
@Configuration(proxyBeanMethods = false)
public class {cap(m)}DatabaseConfig {{

    /** Bean name; every repository of this module injects the database by this qualifier. */
    public static final String DATABASE = "{m}Database";

    @Bean(name = DATABASE, destroyMethod = "close")
    public ModuleDatabase {m}Database(Environment environment) {{
        return ModuleDatabase.open("{m}", environment, {tenant});
    }}

    @Bean
    public ModuleDatabaseHealthIndicator {m}DatabaseHealthIndicator(@Qualifier(DATABASE) ModuleDatabase database) {{
        return new ModuleDatabaseHealthIndicator(database);
    }}
}}
"""

