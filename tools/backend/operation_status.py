"""Writes api/operations-status.md: for every contract operation, whether this build serves it, read from the code.

An operation is served when a controller implements its method with a body that does not throw
NotImplementedException; every other operation answers 501 NOT_IMPLEMENTED at the edge. Run from anywhere:
    python3 tools/backend/operation_status.py
"""
import collections
import glob
import json
import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(HERE + '/../..')
API = REPO + '/api/openapi/'
GENERATED = '// GENERATED by tools/backend/crud'  # gen.py and gen_operations.py
STANDARD = re.compile(r'^(List|Get|Create|Update|Delete)[A-Z]')


def controller_methods():
    """{module: {methodName: 'generated' | 'hand-written' | 'stub'}} from every controller."""
    out = collections.defaultdict(dict)
    for path in glob.glob(REPO + '/backend/*/src/main/java/com/mysms/*/controller/*Controller.java'):
        module = path.split('/backend/')[1].split('/')[0]
        src = open(path).read()
        generated_file = GENERATED in src
        for m in re.finditer(r'    @Override\n    public ResponseEntity<[^\n]*?> (\w+)\((.*?)\n    }\n', src, re.S):
            name, body = m.group(1), m.group(2)
            if 'NotImplementedException' in body:
                kind = 'stub'
            elif generated_file or re.search(r'(Service)\.(list|get|create|update|delete)[A-Z]\w*\(', body):
                kind = 'generated' if generated_file or 'merge_controllers' in src else 'hand-written'
            else:
                kind = 'hand-written'
            out[module][name] = kind
    return out


def skip_reasons():
    report = REPO + '/tools/backend/crud/target/report.json'
    if not os.path.exists(report):
        return {}
    reasons = {}
    for module, items in json.load(open(report)).items():
        for resource, why in items:
            reasons[(module, resource)] = why
    return reasons


def main():
    served = controller_methods()
    standard = json.load(open(REPO + '/api/standard-resources.json'))['resources']
    generated_ops = {op for r in standard for op in r['operations'].values()}
    generated_ops |= {t['operation'] for r in standard for t in r.get('transitions', [])}
    reasons = skip_reasons()
    rows = collections.defaultdict(list)
    totals = collections.Counter()
    for path in sorted(glob.glob(API + '*.yaml')):
        module = os.path.basename(path)[:-5]
        if module in ('common', 'mysms-api', 'redocly'):
            continue
        doc = yaml.safe_load(open(path))
        for p, item in doc['paths'].items():
            for verb, op in item.items():
                if not isinstance(op, dict) or 'operationId' not in op:
                    continue
                oid = op['operationId']
                name = oid.split('.', 1)[1]
                method = name[:1].lower() + name[1:]
                kind = served.get(module, {}).get(method)
                if oid in generated_ops or kind == 'generated':
                    status = 'served (generated)'
                elif kind in ('generated', 'hand-written'):
                    status = 'served (hand-written)'
                else:
                    status = '501'
                note = ''
                if status == '501':
                    if STANDARD.match(name):
                        resource = name.split(re.match(STANDARD, name).group(1), 1)[1]
                        why = reasons.get((module, resource)) or reasons.get((module, resource.rstrip('s')))
                        if not why and resource.endswith('ies'):
                            why = reasons.get((module, resource[:-3] + 'y'))
                        note = 'standard operation not generated' + (': ' + why if why else
                                                                     ': public, platform-staff or extra-parameter variant')
                    else:
                        note = 'workflow / custom operation'
                totals[(module, status.split(' ')[0])] += 1
                rows[module].append((oid, verb.upper(), p, op.get('x-permission', ''), status, note))
    lines = ['# Operation status', '',
             'Generated by `tools/backend/operation_status.py` from the contracts and the controllers of this build — do',
             'not edit by hand. *Served* operations are implemented and covered by component tests against PostgreSQL;',
             'every other operation answers **501 `NOT_IMPLEMENTED`** at the edge, never a misleading 404.', '',
             '| Module | Operations | Served | 501 |', '|---|---:|---:|---:|']
    all_ops = all_served = 0
    for module in sorted(rows):
        n = len(rows[module])
        s = totals[(module, 'served')]
        all_ops += n
        all_served += s
        lines.append('| %s | %d | %d | %d |' % (module, n, s, n - s))
    lines.append('| **all** | **%d** | **%d** | **%d** |' % (all_ops, all_served, all_ops - all_served))
    for module in sorted(rows):
        lines += ['', '## %s' % module, '', '| Operation | Method | Path | Permission | Status | Why not served |',
                  '|---|---|---|---|---|---|']
        for oid, verb, p, perm, status, note in rows[module]:
            lines.append('| `%s` | %s | `%s` | `%s` | %s | %s |' % (oid, verb, p, perm, status, note.replace('|', '/')))
    with open(REPO + '/api/operations-status.md', 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('operations', all_ops, 'served', all_served, '501', all_ops - all_served)


if __name__ == '__main__':
    main()
