// Generates the typed tables core needs from the contracts, so a typo is a compile error:
//   src/generated/permissions.ts  — every x-permission code of the modules' operation tables (ui/05 §5)
//   src/generated/screens.ts      — every screen of ui/02 with its routes and clients (ui/05 §2)
//   src/generated/operations.ts   — the modules that own long-running operations (api/README)
//   src/generated/resources.ts    — the resources served by standard operations (api/standard-resources.json)
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../..');
const outDir = resolve(here, '../src/generated');
mkdirSync(outDir, { recursive: true });
const HEADER = '/* eslint-disable */\n// GENERATED by packages/core/scripts/generate.mjs — do not edit.\n';
const VERBS = ['get', 'put', 'post', 'delete', 'patch'];

// ---- permissions + operation-owning modules from the areas' edge operation tables (owned contract data:
//      backend/<module>/src/main/resources/META-INF/mysms/operations/<area>.json, every contract operation; a
//      backend module serves one or more areas, each the namespace of one SDK client)
const backend = resolve(root, 'backend');
const TABLES = 'src/main/resources/META-INF/mysms/operations';
const moduleOf = new Map();
for (const dir of readdirSync(backend).sort()) {
  if (!existsSync(resolve(backend, dir, TABLES))) continue;
  for (const file of readdirSync(resolve(backend, dir, TABLES)).filter((f) => f.endsWith('.json'))) {
    moduleOf.set(file.slice(0, -'.json'.length), dir);
  }
}
const codes = new Set();
const opModules = new Set();
for (const module of [...moduleOf.keys()].sort()) {
  const table = resolve(backend, moduleOf.get(module), TABLES, `${module}.json`);
  for (const op of JSON.parse(readFileSync(table, 'utf8'))) {
    if (!op.permission) throw new Error(`${op.operationId}: no permission`);
    codes.add(op.permission);
    if (op.method === 'GET' && op.path === `/v1/${module}/operations/{operationId}`) opModules.add(module);
  }
}
const sortedCodes = [...codes].sort();
writeFileSync(
  resolve(outDir, 'permissions.ts'),
  `${HEADER}/** Every permission code used by the API (${sortedCodes.length}). */\n` +
    `export const PERMISSION_CODES = ${JSON.stringify(sortedCodes, null, 2)} as const;\n\n` +
    'export type PermissionCode = (typeof PERMISSION_CODES)[number];\n',
);
const sortedMods = [...opModules].sort();
if (sortedMods.length === 0) throw new Error('no operation-owning modules found');
writeFileSync(
  resolve(outDir, 'operations.ts'),
  `${HEADER}/** Modules that own long-running operations; each serves /v1/<module>/operations. */\n` +
    `export const OPERATION_MODULES = ${JSON.stringify(sortedMods)} as const;\n\n` +
    'export type OperationModule = (typeof OPERATION_MODULES)[number];\n',
);

// ---- screens from the ui/02 inventory tables
const inventory = readFileSync(resolve(root, 'ui/02-navigation-and-screens.md'), 'utf8').split('\n');
const screens = [];
let columns = null;
for (const line of inventory) {
  if (line.startsWith('| ID |')) {
    columns = line
      .split('|')
      .slice(1, -1)
      .map((c) => c.trim());
    continue;
  }
  if (!line.startsWith('|')) {
    columns = null; // a table ends at the first non-table line
    continue;
  }
  if (!/^\| [A-Z]{2,4}-\d{2} \|/.test(line)) continue; // separator or a non-screen table row
  if (!columns) throw new Error(`screen row outside an inventory table: ${line.slice(0, 40)}`);
  const cells = line
    .split('|')
    .slice(1, -1)
    .map((c) => c.trim());
  const cell = (name) => cells[columns.indexOf(name)] ?? '';
  const routes = [...cell('Route').matchAll(/`(\/[^`]*)`/g)].map((m) => m[1]);
  // a few screens are sheets/drawers/wizards inside another screen and have no route of their own
  const placement = routes.length === 0 ? cell('Route').replace(/[()]/g, '').trim() : undefined;
  if (routes.length === 0 && !placement)
    throw new Error(`screen ${cells[0]} has neither a route nor a placement`);
  const clientsCell = columns.includes('Clients') ? cell('Clients') : 'C';
  // 'all' = every client including the platform console (ui/02 §3)
  const clients =
    clientsCell === 'all' ? ['W', 'S', 'P', 'T', 'B', 'C'] : clientsCell.split(/\s+/).filter(Boolean);
  screens.push(
    placement
      ? { id: cells[0], title: cell('Screen'), routes, clients, placement }
      : { id: cells[0], title: cell('Screen'), routes, clients },
  );
}
const ids = new Set(screens.map((s) => s.id));
if (ids.size !== screens.length) throw new Error('duplicate screen id in ui/02');
writeFileSync(
  resolve(outDir, 'screens.ts'),
  `${HEADER}import type { ScreenDef } from '../routes/types';\n\n` +
    `/** The ${screens.length} screens of ui/02 with their routes (web paths are mounted under /app). */\n` +
    `export const SCREENS: readonly ScreenDef[] = ${JSON.stringify(screens, null, 2)};\n`,
);
// ---- generic record screens: every resource whose standard operations the backend serves (api/standard-resources.json),
//      described by the OpenAPI document the area's backend build wrote from its code (springdoc), so the backend
//      build runs first: backend/<module>/target/openapi/<area>/api-docs.yml
const standard = JSON.parse(readFileSync(resolve(root, 'api/standard-resources.json'), 'utf8')).resources;
const docs = new Map();
const docOf = (module) => {
  if (!docs.has(module)) {
    const file = resolve(backend, moduleOf.get(module) ?? module, `target/openapi/${module}/api-docs.yml`);
    if (!existsSync(file))
      throw new Error(`no OpenAPI document of ${module}: build the backend first (mvn install)`);
    docs.set(module, parse(readFileSync(file, 'utf8'), { maxAliasCount: -1 }));
  }
  return docs.get(module);
};
// OpenAPI 3.1 states a nullable value as a list of types ([string, 'null']); the kind is the non-null one
const typeOf = (p) => (Array.isArray(p.type) ? p.type.find((t) => t !== 'null') : p.type);
const humanize = (name) => {
  const words = name
    .replace(/Id$/, '')
    .replace(/^is([A-Z])/, '$1')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
};
const fieldOf = (doc, name, prop, required, writable) => {
  let p = prop;
  if (p.$ref) p = doc.components.schemas[p.$ref.split('/').pop()];
  if (!p) return null;
  const type = typeOf(p);
  let kind;
  if (p.enum) kind = 'enum';
  else if (type === 'boolean') kind = 'boolean';
  else if (type === 'integer') kind = p.format === 'int64' ? 'decimal' : 'integer';
  else if (type === 'number' || p.format === 'decimal' || p.format === 'int64') kind = 'decimal';
  else if (type === 'string' && p.format === 'date') kind = 'date';
  else if (type === 'string' && p.format === 'date-time') kind = 'datetime';
  else if (type === 'string' && p.format === 'time') kind = 'time';
  else if (type === 'string' && p.format === 'uuid') kind = 'id';
  else if (type === 'string') kind = 'text';
  else return null; // arrays and objects are edited in their own screens
  const field = { name, label: humanize(name), kind };
  if (p.enum) {
    field.values = p.enum.filter((v) => v !== null);
    // wire values shown as words, never raw (ui/05 rules): fixed_amount → Fixed amount
    field.valueLabels = field.values.map((v) => {
      const words = String(v).replace(/[_-]+/g, ' ');
      return words.charAt(0).toUpperCase() + words.slice(1);
    });
  }
  if (p.maxLength) field.maxLength = p.maxLength;
  if (required) field.required = true;
  if (prop.readOnly || p.readOnly) field.readOnly = true;
  if (prop.writeOnly || p.writeOnly) field.writeOnly = true;
  if (writable) field.writable = true;
  return field;
};
const resources = [];
for (const r of standard) {
  const doc = docOf(r.module);
  const byId = {};
  for (const [path, item] of Object.entries(doc.paths ?? {}))
    for (const verb of VERBS)
      if (item[verb])
        byId[item[verb].operationId] = {
          path,
          permission: item[verb]['x-permission'],
          request: item[verb].requestBody?.content?.['application/json']?.schema?.$ref?.split('/').pop(),
          ifMatch: [...(item.parameters ?? []), ...(item[verb].parameters ?? [])].some(
            (p) => p.$ref?.endsWith('/IfMatch') || p.name === 'If-Match',
          ),
        };
  const schema = doc.components.schemas[r.resource];
  const update = doc.components.schemas[`${r.resource}Update`]?.properties ?? {};
  const required = new Set(schema.required ?? []);
  const skip = new Set(['id', 'etag', 'createTime', 'updateTime', 'createdBy', 'updatedBy']);
  const fields = Object.entries(schema.properties ?? {})
    .filter(([name]) => !skip.has(name))
    .map(([name, prop]) => fieldOf(doc, name, prop, required.has(name), name in update))
    .filter(Boolean);
  for (const f of fields)
    if (f.kind === 'boolean' && f.name in (r.booleanDefaults ?? {}))
      f.defaultValue = r.booleanDefaults[f.name];
  const ops = {};
  for (const [kind, operationId] of Object.entries(r.operations)) {
    const found = byId[operationId];
    ops[kind] = found && { path: found.path, permission: found.permission };
  }
  if (Object.values(ops).some((o) => !o)) throw new Error(`${r.module}.${r.resource}: operation missing`);
  // generated state transitions (api/state-machines.md): offered on a row only in the states their guard allows
  const actions = (r.transitions ?? []).map((tr) => {
    const found = byId[tr.operation];
    if (!found) throw new Error(`${tr.operation}: operation missing`);
    const request = found.request ? doc.components.schemas[found.request] : undefined;
    const props = request?.properties ?? {};
    const needed = new Set(request?.required ?? []);
    const params = Object.entries(props)
      .filter(([name]) => name !== 'etag' && name !== 'reason')
      .map(([name, prop]) => fieldOf(doc, name, prop, needed.has(name), true))
      .filter(Boolean);
    return {
      operation: tr.operation,
      label: humanize(tr.step),
      path: found.path,
      permission: found.permission,
      guard: tr.guard,
      etag: 'etag' in props,
      ifMatch: found.ifMatch,
      reason: 'reason' in props,
      params,
    };
  });
  resources.push({
    key: `${r.module}.${r.resource}`,
    module: r.module,
    label: humanize(r.resource),
    ...(r.parent ? { parent: r.parent } : {}),
    scope: r.scope,
    ops,
    fields,
    ...(actions.length ? { actions } : {}),
    // partitioned tables: every list must name a range of this field (the server answers 400 without one)
    ...(r.partition
      ? {
          partition: {
            field: r.partition,
            kind: schema.properties?.[r.partition]?.format === 'date' ? 'date' : 'datetime',
          },
        }
      : {}),
  });
}
writeFileSync(
  resolve(outDir, 'resources.ts'),
  `${HEADER}import type { ResourceDef } from '../records/types';

` +
    `/** The ${resources.length} resources whose standard operations are served, for the generic record screens. */
` +
    `export const RESOURCES: readonly ResourceDef[] = ${JSON.stringify(resources)};
`,
);
const listPermissions = [...new Set(resources.map((r) => r.ops.List?.permission).filter(Boolean))].sort();
writeFileSync(
  resolve(outDir, 'recordPermissions.ts'),
  `${HEADER}/** The list permissions of the record screens (a small table, so the navigation need not load RESOURCES). */\n` +
    `export const RECORD_PERMISSIONS: readonly string[] = ${JSON.stringify(listPermissions)};\n`,
);
console.warn(
  `core: ${resources.length} record resources, ${sortedCodes.length} permission codes, ${sortedMods.length} operation modules, ${screens.length} screens`,
);
