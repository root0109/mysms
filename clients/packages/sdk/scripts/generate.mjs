// Generates the MySMS TypeScript SDK with OpenAPI Generator (https://github.com/OpenAPITools/openapi-generator),
// generator `typescript-fetch`, pinned in ../openapitools.json. One client per area (one contract: an operation
// table, a /v1/<area> prefix; a backend module serves one or more areas), generated from the OpenAPI document the
// area's backend build wrote from its code (backend/<module>/target/openapi/<area>/api-docs.yml, written by its
// <Area>OpenApiComponentTest from springdoc), all in a single JVM run (`batch`). The backend build therefore runs
// first: `mvn install` in backend/, then `pnpm generate`.
//
//   src/generated/<area>/apis, models, index.ts     — one namespace per area
//   src/generated/runtime.ts                        — the single shared runtime (every module re-exports it,
//                                                     so ResponseError/Configuration are one class each)
//   src/generated/index.ts                          — `export * as <module> from './<module>'`
//
// Requires Java 17+ on PATH (the generator is a Java program). The generator jar is the one the
// @openapitools/openapi-generator-cli package downloads (version from openapitools.json); set
// OPENAPI_GENERATOR_JAR to use a local copy instead.
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const backend = resolve(pkg, '../../../backend');
const TABLES = 'src/main/resources/META-INF/mysms/operations';
const out = resolve(pkg, 'src/generated');
const HEADER = '/* eslint-disable */\n// GENERATED by packages/sdk/scripts/generate.mjs — do not edit.\n';

// the areas: each edge operation table of a backend module names one (the SDK keeps a namespace per area)
const moduleOf = new Map();
for (const dir of readdirSync(backend).filter((d) => existsSync(resolve(backend, d, TABLES)))) {
  for (const file of readdirSync(resolve(backend, dir, TABLES)).filter((f) => f.endsWith('.json'))) {
    moduleOf.set(file.slice(0, -'.json'.length), dir);
  }
}
const modules = [...moduleOf.keys()].sort();
if (modules.length !== 22) throw new Error(`expected 22 areas, found ${modules.length}`);
const specOf = (area) => resolve(backend, moduleOf.get(area), `target/openapi/${area}/api-docs.yml`);
const missing = modules.filter((m) => !existsSync(specOf(m)));
if (missing.length > 0) {
  throw new Error(
    `no OpenAPI document for ${missing.join(', ')}: build the backend first (mvn install in backend/)`,
  );
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// ---- the generator jar: OPENAPI_GENERATOR_JAR, else the CLI's download of the pinned version
function generatorJar() {
  if (process.env.OPENAPI_GENERATOR_JAR) return process.env.OPENAPI_GENERATOR_JAR;
  const require = createRequire(import.meta.url);
  const cliDir = dirname(require.resolve('@openapitools/openapi-generator-cli/package.json'));
  const version = JSON.parse(readFileSync(resolve(pkg, 'openapitools.json'), 'utf8'))['generator-cli']
    .version;
  const jarPath = resolve(cliDir, 'versions', `${version}.jar`);
  if (!existsSync(jarPath)) {
    // the CLI downloads the pinned version on first use
    execFileSync(process.execPath, [resolve(cliDir, 'main.js'), 'version'], { stdio: 'inherit', cwd: pkg });
  }
  if (!existsSync(jarPath)) throw new Error(`OpenAPI Generator ${version} was not downloaded to ${jarPath}`);
  return jarPath;
}
const jar = generatorJar();

// ---- one batch config per module
const work = mkdtempSync(join(tmpdir(), 'mysms-sdk-'));
const configs = modules.map((module) => {
  const spec = specOf(module);
  const file = join(work, `${module}.config.json`);
  writeFileSync(
    file,
    JSON.stringify({
      generatorName: 'typescript-fetch',
      inputSpec: spec,
      outputDir: resolve(out, module),
      // keep the contract's property names; dates stay ISO strings exactly as the API sends them
      additionalProperties: {
        supportsES6: true,
        modelPropertyNaming: 'original',
        paramNaming: 'camelCase',
        useSingleRequestParameter: true,
        prefixParameterInterfaces: true,
        removeOperationIdPrefix: true,
        removeOperationIdPrefixDelimiter: '.',
        removeOperationIdPrefixCount: 1,
        stringEnums: false, // enums as `as const` objects + literal-union types, so plain strings type-check
        withoutRuntimeChecks: true,
        hideGenerationTimestamp: true,
      },
      typeMappings: { date: 'string', DateTime: 'string', Date: 'string' },
    }),
  );
  return file;
});

try {
  execFileSync('java', ['-jar', jar, 'batch', '--fail-fast', ...configs], { stdio: 'inherit' });
} finally {
  rmSync(work, { recursive: true, force: true });
}

// ---- one shared runtime: every module's runtime.ts must be identical apart from the spec banner and BASE_PATH
const normalise = (text) =>
  text
    .replace(/^\/\*\*[\s\S]*?\*\/\n/m, '') // the per-spec banner comment
    .replace(/^export const BASE_PATH = .*$/m, "export const BASE_PATH = '';");
let shared = null;
for (const module of modules) {
  const dir = resolve(out, module);
  const runtime = normalise(readFileSync(resolve(dir, 'runtime.ts'), 'utf8'));
  if (shared === null) shared = runtime;
  else if (runtime !== shared) throw new Error(`runtime.ts of ${module} differs from the others`);
  writeFileSync(resolve(dir, 'runtime.ts'), `${HEADER}export * from '../runtime';\n`);
  rmSync(resolve(dir, '.openapi-generator'), { recursive: true, force: true });
  rmSync(resolve(dir, '.openapi-generator-ignore'), { force: true });
  rmSync(resolve(dir, 'docs'), { recursive: true, force: true });
}
// BASE_PATH is never used: the app always passes its own basePath.
// The generator's runtime is written for a less strict compiler profile than ours (noImplicitOverride,
// noUncheckedIndexedAccess), so its body is not re-checked; its exported types are still checked at every use.
writeFileSync(resolve(out, 'runtime.ts'), `${HEADER}// @ts-nocheck\n${shared}`);
writeFileSync(
  resolve(out, 'index.ts'),
  `${HEADER}export * from './runtime';\n` + modules.map((m) => `export * as ${m} from './${m}';\n`).join(''),
);
console.warn(`sdk: generated ${modules.length} module clients into ${out}`);
