import {
  elevation,
  fonts,
  intents,
  motion,
  palette,
  radius,
  rowHeight,
  space,
  typeScale,
  type Mode,
} from './tokens';

/** camelCase → kebab-case; a trailing digit stays attached (`surface2` → `surface-2` is spelled out in the
 *  palette name map below, `h2` stays `h2`). */
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/^-/, '');
const PALETTE_NAMES: Record<string, string> = { surface2: 'surface-2' };

/** CSS custom properties `--sms-<group>-<name>` (ui/04 §2) for one mode. */
export function cssVariables(mode: Mode): Record<string, string> {
  const v: Record<string, string> = {};
  for (const [k, value] of Object.entries(palette[mode]))
    v[`--sms-color-${PALETTE_NAMES[k] ?? kebab(k)}`] = value;
  for (const [intent, c] of Object.entries(intents[mode])) {
    v[`--sms-intent-${intent}`] = c.base;
    v[`--sms-intent-on-${intent}`] = c.on;
    v[`--sms-intent-${intent}-container`] = c.container;
    v[`--sms-intent-on-${intent}-container`] = c.onContainer;
  }
  if (mode === 'light') {
    for (const [name, [size, line, weight]] of Object.entries(typeScale)) {
      // every text size follows the user's text-size setting (100–150 %, ui/04 §9) through --sms-text-scale
      v[`--sms-font-${kebab(name)}`] =
        `${weight} calc(${size}px * var(--sms-text-scale)) / calc(${line}px * var(--sms-text-scale)) ` +
        `var(--sms-font-family-${name === 'mono' ? 'mono' : 'ui'})`;
    }
    v['--sms-text-scale'] = '1';
    v['--sms-row-height'] = `${rowHeight.comfortable}px`;
    v['--sms-font-family-ui'] = fonts.ui;
    v['--sms-font-family-mono'] = fonts.mono;
    space.forEach((s, i) => (v[`--sms-space-${i}`] = `${s}px`));
    for (const [k, r] of Object.entries(radius)) v[`--sms-radius-${k}`] = `${r}px`;
    elevation.forEach((e, i) => (v[`--sms-elevation-${i}`] = e));
    v['--sms-motion-micro'] = `${motion.micro}ms`;
    v['--sms-motion-overlay'] = `${motion.overlay}ms`;
    v['--sms-motion-page'] = `${motion.page}ms`;
    v['--sms-motion-easing'] = motion.easing;
  }
  return v;
}

const block = (selector: string, vars: Record<string, string>) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, val]) => `  ${k}: ${val};`)
    .join('\n')}\n}\n`;

const NO_MOTION = '{ --sms-motion-micro: 0ms; --sms-motion-overlay: 0ms; --sms-motion-page: 0ms; }';

/**
 * The stylesheet: light by default; dark from the OS unless the user picked a theme; explicit `data-theme` light,
 * dark or high-contrast; `data-density` compact; `data-reduced-motion` true; and `--sms-text-scale` (ui/04 §9).
 */
export function tokensCss(): string {
  return [
    '/* GENERATED by @mysms/tokens — do not edit. */\n',
    block(':root', cssVariables('light')),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', cssVariables('dark'))
      .split('\n')
      .map((l) => (l ? `  ${l}` : l))
      .join('\n')}}\n`,
    block(':root[data-theme="dark"]', cssVariables('dark')),
    block(':root[data-theme="high-contrast"]', cssVariables('highContrast')),
    block(':root[data-density="compact"]', { '--sms-row-height': `${rowHeight.compact}px` }),
    `@media (prefers-reduced-motion: reduce) {\n  :root ${NO_MOTION}\n}\n`,
    `:root[data-reduced-motion="true"] ${NO_MOTION}\n`,
  ].join('\n');
}
